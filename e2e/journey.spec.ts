import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
test('demo workflow, languages, persistence, exports and screenshots',async({page})=>{
 await page.goto('/');
 await page.screenshot({path:'screenshots/dashboard.png',fullPage:true});
 await page.getByRole('button',{name:'ҚАЗ'}).click();
 await page.getByRole('button',{name:'Демо жобаны ашу'}).first().click();
 await page.getByRole('button',{name:'Жариялауға дейінгі тексеру'}).click();
 await page.getByRole('button',{name:'Тексеруді бастау'}).click();
 await expect(page.getByText('The abstract does not explicitly identify a contribution.')).toBeVisible();
 await page.screenshot({path:'screenshots/review.png',fullPage:true});
 await page.getByRole('button',{name:'РУС'}).click();
 await page.getByRole('button',{name:'Замечания рецензентов',exact:true}).click();
 await page.getByRole('button',{name:/The abstract does not clearly identify/}).click();
 await expect(page.getByText('Clarifies existing text without adding experimental claims.')).toBeVisible();
 await page.screenshot({path:'screenshots/revision.png',fullPage:true});
 await page.getByRole('button',{name:'Применить исправление'}).click();
 await page.getByRole('button',{name:'Рукопись',exact:true}).click();
 await expect(page.getByText(/Its contribution is a description/)).toBeVisible();
 await page.getByRole('button',{name:'Ответ рецензентам',exact:true}).click();
 await expect(page.locator('textarea').first()).toHaveValue(/We revised the Abstract section/);
 await page.screenshot({path:'screenshots/response.png',fullPage:true});
 await page.getByRole('button',{name:'Центр экспорта',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:/Скачать рукопись DOCX/}).click();
 const download=await downloadPromise; const path=await download.path();
 expect(execFileSync('unzip',['-p',path!,'word/document.xml'],{encoding:'utf8'})).toContain('Its contribution is a description');
 await page.reload();await expect(page.getByText('1 Принятые правки')).toBeVisible();
 await page.getByRole('button',{name:'EN',exact:true}).click();
 await page.getByRole('button',{name:'Manuscript',exact:true}).click();
 await expect(page.getByText(/Its contribution is a description/)).toBeVisible();
});
